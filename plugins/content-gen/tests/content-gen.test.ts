import { afterEach, describe, expect, spyOn, test } from 'bun:test';
import { chmod, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { type Content, ContentSchema, type Doc } from '@gobing-ai/kk-core';
import { logger } from '@gobing-ai/utils';
import { runInvoke } from '../../../apps/cli/src/invoke';
import { generateWithTechnicalContentSkill, main, processGeneratorIO } from '../src/index';

const FIXTURES_DIR = join(import.meta.dir, 'fixtures');
const IN_FILE = join(FIXTURES_DIR, 'docs.json');
const OUT_FILE = join(import.meta.dir, 'output.json');
const MOCK_SPUR = join(FIXTURES_DIR, 'spur');
const ORIGINAL_ARGV = process.argv;
const ORIGINAL_SPUR_BIN = process.env.KNOWLEDGE_KIT_SPUR_BIN;

async function writeMockSpur(result: { exitCode: number; stdout: string; stderr: string }): Promise<void> {
    await writeFile(
        MOCK_SPUR,
        `#!/usr/bin/env bun\nconsole.log(${JSON.stringify(JSON.stringify({ ...result, durationMs: 1 }))});\n`,
        'utf-8',
    );
    await chmod(MOCK_SPUR, 0o755);
    process.env.KNOWLEDGE_KIT_SPUR_BIN = MOCK_SPUR;
}

afterEach(async () => {
    process.argv = ORIGINAL_ARGV;
    if (ORIGINAL_SPUR_BIN === undefined) delete process.env.KNOWLEDGE_KIT_SPUR_BIN;
    else process.env.KNOWLEDGE_KIT_SPUR_BIN = ORIGINAL_SPUR_BIN;
    await rm(FIXTURES_DIR, { recursive: true, force: true });
    await rm(OUT_FILE, { force: true });
});

describe('content-gen plugin adapter', () => {
    test('knowledge-kit invoke delegates to the stand-in boundary and writes ContentSchema output', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        const docs: Doc[] = [
            {
                id: 'doc-1',
                title: 'Architecture Overview',
                body: 'Content for architecture overview.',
                sourceUri: 'https://example.com/arch',
            },
        ];
        const content = {
            title: 'Architecture Overview',
            body: '# Architecture Overview\n\nGenerated by stages 0-3.',
            format: 'markdown',
            references: [{ url: docs[0]?.sourceUri, title: docs[0]?.title, cite: docs[0]?.id }],
        };
        await writeFile(IN_FILE, JSON.stringify(docs), 'utf-8');
        await writeMockSpur({ exitCode: 0, stdout: JSON.stringify(content), stderr: '' });

        const code = await runInvoke({
            plugin: 'content-gen',
            inPath: IN_FILE,
            outPath: OUT_FILE,
            pluginsRoot: join(import.meta.dir, '../..'),
        });

        expect(code).toBe(0);
        expect(ContentSchema.parse(JSON.parse(await readFile(OUT_FILE, 'utf-8')))).toEqual({
            ...content,
            metadata: {
                generator: 'wt:technical-content-creation',
                stageCount: 4,
                docIds: ['doc-1'],
            },
        });
    });

    test('empty input writes the contract notice without invoking the stand-in', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeFile(IN_FILE, '[]', 'utf-8');
        const generate = async () => {
            throw new Error('must not run');
        };

        await processGeneratorIO(IN_FILE, OUT_FILE, generate);

        const result = ContentSchema.parse(JSON.parse(await readFile(OUT_FILE, 'utf-8')));
        expect(result.body).toContain('No documents provided for generation.');
        expect(result.references).toEqual([]);
    });

    test('stand-in failure returns non-zero, reaches stderr, and leaves no output', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeFile(IN_FILE, JSON.stringify([{ id: '1', body: 'test' }]), 'utf-8');
        await writeFile(OUT_FILE, 'stale', 'utf-8');
        await writeMockSpur({ exitCode: 1, stdout: '', stderr: 'Engine stage 2 failed' });
        const errorSpy = spyOn(logger, 'error').mockImplementation(() => {});

        try {
            const code = await runInvoke({
                plugin: 'content-gen',
                inPath: IN_FILE,
                outPath: OUT_FILE,
                pluginsRoot: join(import.meta.dir, '../..'),
            });
            expect(code).toBe(1);
            expect(errorSpy.mock.calls.flat().join(' ')).toContain('Engine stage 2 failed');
            expect(await Bun.file(OUT_FILE).exists()).toBe(false);
        } finally {
            errorSpy.mockRestore();
        }
    });

    test('invalid stand-in output fails before writing', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeFile(IN_FILE, JSON.stringify([{ id: '1', body: 'test' }]), 'utf-8');
        const generate = async () => ({ title: 'missing body' }) as Content;

        await expect(processGeneratorIO(IN_FILE, OUT_FILE, generate)).rejects.toThrow();
        expect(await Bun.file(OUT_FILE).exists()).toBe(false);
    });

    test('skill runner accepts fenced Content JSON', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeFile(IN_FILE, JSON.stringify([{ id: '1', body: 'test' }]), 'utf-8');
        await writeMockSpur({ exitCode: 0, stdout: '```json\n{"body":"draft"}\n```', stderr: '' });

        expect(await generateWithTechnicalContentSkill([{ id: '1', body: 'test' }], IN_FILE)).toEqual({
            body: 'draft',
            title: 'Generated Knowledge Kit Synthesis',
            format: 'markdown',
            references: [{ cite: '1' }],
            metadata: {
                generator: 'wt:technical-content-creation',
                stageCount: 4,
                docIds: ['1'],
            },
        });
    });

    test('skill runner accepts prose-wrapped fenced Content JSON', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeMockSpur({
            exitCode: 0,
            stdout: 'Stages 0-3 complete.\n\n```json\n{"body":"draft"}\n```\n\nDone.',
            stderr: '',
        });

        expect(await generateWithTechnicalContentSkill([{ id: '1', body: 'test' }], IN_FILE)).toEqual({
            body: 'draft',
            title: 'Generated Knowledge Kit Synthesis',
            format: 'markdown',
            references: [{ cite: '1' }],
            metadata: {
                generator: 'wt:technical-content-creation',
                stageCount: 4,
                docIds: ['1'],
            },
        });
    });

    test('skill runner surfaces agent failure details', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeMockSpur({ exitCode: 1, stdout: '', stderr: 'Engine stage 2 failed' });

        await expect(generateWithTechnicalContentSkill([{ id: '1', body: 'test' }], IN_FILE)).rejects.toThrow(
            'Engine stage 2 failed',
        );
    });

    test('malformed input fails before invoking the stand-in', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeFile(IN_FILE, JSON.stringify([{ title: 'missing id and body' }]), 'utf-8');
        const generate = async () => {
            throw new Error('must not run');
        };

        await expect(processGeneratorIO(IN_FILE, OUT_FILE, generate)).rejects.toThrow();
        expect(await Bun.file(OUT_FILE).exists()).toBe(false);
    });

    test('main reports missing arguments without terminating the process', async () => {
        process.argv = ['bun', 'index.ts'];
        const errorSpy = spyOn(logger, 'error').mockImplementation(() => {});
        try {
            expect(await main()).toBe(1);
            expect(errorSpy).toHaveBeenCalled();
        } finally {
            errorSpy.mockRestore();
        }
    });

    test('main returns success after writing validated skill output', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeFile(IN_FILE, JSON.stringify([{ id: '1', body: 'test' }]), 'utf-8');
        await writeMockSpur({ exitCode: 0, stdout: '{"body":"draft"}', stderr: '' });
        process.argv = ['bun', 'index.ts', '--in', IN_FILE, '--out', OUT_FILE];

        expect(await main()).toBe(0);
        expect(ContentSchema.parse(JSON.parse(await readFile(OUT_FILE, 'utf-8'))).body).toBe('draft');
    });

    test('main returns failure and removes stale output', async () => {
        await mkdir(FIXTURES_DIR, { recursive: true });
        await writeFile(IN_FILE, JSON.stringify([{ id: '1', body: 'test' }]), 'utf-8');
        await writeFile(OUT_FILE, 'stale', 'utf-8');
        await writeMockSpur({ exitCode: 1, stdout: '', stderr: 'Engine stage 2 failed' });
        process.argv = ['bun', 'index.ts', '--in', IN_FILE, '--out', OUT_FILE];
        const errorSpy = spyOn(logger, 'error').mockImplementation(() => {});

        try {
            expect(await main()).toBe(1);
            expect(errorSpy.mock.calls.flat().join(' ')).toContain('Engine stage 2 failed');
            expect(await Bun.file(OUT_FILE).exists()).toBe(false);
        } finally {
            errorSpy.mockRestore();
        }
    });
});
